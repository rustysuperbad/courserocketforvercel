import { z } from "zod";
import { levelSchema, specStatusSchema, type LearnerSpec } from "./schemas";

export type EvalCorpus = "in" | "out";
export type EvalLessonOutcome = "empty_reject" | "intake_only" | "blocked" | "quality";

export const evalExpectedSchema = z.object({
  intakeStatus: specStatusSchema,
  topic: z.string(),
  topicVariants: z.array(z.string()).min(1).max(12),
  level: levelSchema,
  constraints: z.array(z.string()),
  ignoredRequests: z.array(z.string()).max(4),
  lessonOutcome: z.enum(["empty_reject", "intake_only", "blocked", "quality"]),
  ingestionRequest: z.boolean(),
  treatAsData: z.array(z.string()),
  mustCover: z.array(z.string()),
  mustNotProduce: z.array(z.string()),
  omitOffPath: z.array(z.string()),
  lessonLanguage: z.enum(["en"]).optional(),
  d1Treatment: z.enum(["short"]).optional(),
}).strict();
export type EvalExpected = z.infer<typeof evalExpectedSchema>;

export const ragEvalGoalSchema = z.object({
  id: z.string().regex(/^g\d{2}$/),
  text: z.string(),
  paraphrase: z.string(),
  tag: z.string().min(2),
  corpus: z.enum(["in", "out"]),
  expected: evalExpectedSchema,
}).strict();
export type RagEvalGoal = z.infer<typeof ragEvalGoalSchema>;

export const ragEvalGoalsFileSchema = z.array(ragEvalGoalSchema).min(33);

const ok = (partial: {
  topic: string;
  topicVariants?: string[];
  level: LearnerSpec["level"];
  constraints: string[];
  lessonOutcome: "blocked" | "quality";
  ingestionRequest?: boolean;
  treatAsData?: string[];
  mustCover?: string[];
  mustNotProduce?: string[];
  omitOffPath?: string[];
  ignoredRequests?: string[];
  lessonLanguage?: "en";
  d1Treatment?: "short";
}): EvalExpected => ({
  intakeStatus: "ok",
  topic: partial.topic,
  topicVariants: [partial.topic, ...(partial.topicVariants || [])],
  level: partial.level,
  constraints: partial.constraints,
  ignoredRequests: partial.ignoredRequests || [],
  lessonOutcome: partial.lessonOutcome,
  ingestionRequest: partial.ingestionRequest ?? partial.lessonOutcome === "blocked",
  treatAsData: partial.treatAsData || [],
  mustCover: partial.mustCover || [],
  mustNotProduce: partial.mustNotProduce || [],
  omitOffPath: partial.omitOffPath || [],
  ...(partial.lessonLanguage ? { lessonLanguage: partial.lessonLanguage } : {}),
  ...(partial.d1Treatment ? { d1Treatment: partial.d1Treatment } : {}),
});

const stop = (status: LearnerSpec["status"], lessonOutcome: "empty_reject" | "intake_only"): EvalExpected => ({
  intakeStatus: status,
  topic: "",
  topicVariants: [""],
  level: "beginner",
  constraints: [],
  ignoredRequests: [],
  lessonOutcome,
  ingestionRequest: false,
  treatAsData: [],
  mustCover: [],
  mustNotProduce: [],
  omitOffPath: [],
});

